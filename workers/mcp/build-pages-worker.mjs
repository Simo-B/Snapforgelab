// Builds _worker.js (single file, for the Cloudflare Pages project in advanced mode) from
// worker.js + deep-scan.js. Run after editing either:  node build-pages-worker.mjs
// deep-scan.js is wrapped in its own scope so its names never clash with worker.js.
import { readFileSync, writeFileSync } from "node:fs";
const IMPORT_RE = /^import \{([^}]+)\} from "\.\/deep-scan\.js";\n/m;
const deep = readFileSync(new URL("./deep-scan.js", import.meta.url), "utf8").replace(/^export (?=(async function|function|const|class) )/gm, "");
const workerSrc = readFileSync(new URL("./worker.js", import.meta.url), "utf8");
const m = workerSrc.match(IMPORT_RE);
if (!m) throw new Error("deep-scan import not found in worker.js");
const names = m[1].trim();
const worker = workerSrc.replace(IMPORT_RE, `const {${names}} = __DeepScan;\n`);
if (/^import /m.test(worker) || /^export (?!default)/m.test(deep)) throw new Error("unexpected import/export left");
writeFileSync(new URL("./_worker.js", import.meta.url),
  "// GENERATED by build-pages-worker.mjs from worker.js + deep-scan.js. Do not edit by hand.\n\n" +
  "const __DeepScan = (() => {\n" + deep + `\nreturn {${names}};\n})();\n\n` + worker);
console.log("_worker.js written");
