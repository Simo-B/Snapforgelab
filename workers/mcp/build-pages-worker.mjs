// Builds _worker.js (single-file bundle for Cloudflare Pages in advanced mode) from
// worker.js and its local ES modules in topological dependency order.
// Run after editing any module in workers/mcp/:  node build-pages-worker.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MODULES = ["deep-scan.js", "full-scan.js", "storage.js", "paypal.js"];
const nsFor = (file) => "__Mod_" + file.replace(/\.js$/, "").replace(/[^A-Za-z0-9_]/g, "_");

function rewriteImports(src) {
  return src.replace(/^import\s*\{([\s\S]*?)\}\s*from\s*"\.\/([A-Za-z0-9._\-]+\.js)";\r?\n/gm, (_, spec, modFile) => {
    if (!MODULES.includes(modFile)) throw new Error(`Unknown local import: ./${modFile}`);
    const cleaned = spec.replace(/\s+/g, " ").trim();
    return `const { ${cleaned} } = ${nsFor(modFile)};\n`;
  });
}

function wrapModule(file) {
  const raw = readFileSync(new URL(`./${file}`, import.meta.url), "utf8");
  const exported = [];
  const stripped = rewriteImports(raw).replace(
    /^export\s+(?:async\s+function|function|const|let|class)\s+([A-Za-z0-9_]+)/gm,
    (full, name) => {
      exported.push(name);
      return full.replace(/^export\s+/, "");
    }
  );
  if (/^import\s/m.test(stripped) || /^export\s/m.test(stripped)) {
    throw new Error(`Unexpected leftover import/export in ${file}`);
  }
  return `const ${nsFor(file)} = (() => {\n${stripped}\nreturn { ${exported.join(", ")} };\n})();\n`;
}

const chunks = MODULES.map(wrapModule);
const workerRaw = readFileSync(new URL("./worker.js", import.meta.url), "utf8");
const workerBody = rewriteImports(workerRaw);
if (/^import\s/m.test(workerBody) || /^export\s+(?!default\b)/m.test(workerBody)) {
  throw new Error("Unexpected leftover import/export in worker.js");
}

const out =
  "// GENERATED by build-pages-worker.mjs from worker.js + local modules. Do not edit by hand.\n\n" +
  chunks.join("\n") +
  "\n" +
  workerBody;

writeFileSync(new URL("./_worker.js", import.meta.url), out);
console.log("_worker.js written");
